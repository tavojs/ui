import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { pathToFileURL } from "node:url";
import { runNativeCli } from "../dist/cli/index.js";

test("generates an automatic React Native config module", async () => {
  const dir = join(tmpdir(), `tavo-rn-config-${Date.now()}`);
  await mkdir(dir, { recursive: true });

  const configPath = join(dir, "tavo-ui.config.json");
  const outPath = join(dir, "auto-config.js");
  await writeFile(
    configPath,
    JSON.stringify({
      preset: "mobile",
      defaultTheme: "dark",
      color: {
        light: { primary: "#116a67" }
      }
    })
  );

  await runNativeCli(["generate", "--config", configPath, "--out", outPath]);

  const source = await readFile(outPath, "utf8");
  assert.match(source, /generated by tavo-ui native generate/);
  const declaration = await readFile(join(dir, "auto-config.d.ts"), "utf8");
  assert.match(declaration, /declare const autoConfig/);
  assert.match(declaration, /from "@tavojs\/ui-react-native"/);

  const imported = await import(`${pathToFileURL(outPath).href}?cache=${Date.now()}`);
  assert.equal(imported.default.defaultTheme, "dark");
  assert.equal(imported.default.color.light.primary, "#116a67");
});

test("writes the default generated config into the project working directory", async () => {
  const dir = join(tmpdir(), `tavo-rn-default-output-${Date.now()}`);
  await mkdir(dir, { recursive: true });
  await writeFile(join(dir, "tavo-ui.config.json"), JSON.stringify({ color: { light: { primary: "#116a67" } } }));

  await runNativeCli(["generate"], dir);

  assert.match(await readFile(join(dir, "tavo-ui.generated.js"), "utf8"), /export default autoConfig/);
  assert.match(await readFile(join(dir, "tavo-ui.generated.d.ts"), "utf8"), /TavoUiThemeConfig/);
});

test("validates native CLI option values and output module extensions", async () => {
  await assert.rejects(() => runNativeCli(["generate", "--out"]), /Missing value for --out/);
  await assert.rejects(() => runNativeCli(["generate", "--config", "--out", "theme.js"]), /Missing value for --config/);

  const dir = join(tmpdir(), `tavo-rn-output-${Date.now()}`);
  await mkdir(dir, { recursive: true });
  const configPath = join(dir, "tavo-ui.config.json");
  await writeFile(configPath, JSON.stringify({ color: { light: { primary: "#116a67" } } }));

  const mjsPath = join(dir, "auto-config.mjs");
  await runNativeCli(["generate", "--config", configPath, "--out", mjsPath]);
  assert.match(await readFile(mjsPath, "utf8"), /export default autoConfig/);
  assert.match(await readFile(join(dir, "auto-config.d.mts"), "utf8"), /export default autoConfig/);

  const cjsPath = join(dir, "auto-config.cjs");
  await runNativeCli(["generate", "--config", configPath, "--out", cjsPath]);
  assert.match(await readFile(cjsPath, "utf8"), /module\.exports = autoConfig/);
  assert.match(await readFile(join(dir, "auto-config.d.cts"), "utf8"), /export = autoConfig/);

  await assert.rejects(
    () => runNativeCli(["generate", "--config", configPath, "--out", join(dir, "auto-config")]),
    /must end in \.js, \.mjs, or \.cjs/
  );
});
