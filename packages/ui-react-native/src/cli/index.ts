#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, isAbsolute, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { buildThemeTokens, type TavoUiThemeConfig } from "@tavojs/ui-core";

const CONFIG_CANDIDATES = ["tavo-ui.config.json", "tavo-ui.config.mjs", "tavo-ui.config.js", "tavo-ui.config.cjs"];

type CliOptions = {
  cwd: string;
  config?: string;
  out?: string;
  help?: boolean;
};

function safeErrorMessage(error: unknown): string {
  const message = error instanceof Error ? error.message : String(error);
  return message.replace(/[\u0000-\u0008\u000b-\u000d\u000e-\u001f\u007f-\u009f]/g, "");
}

function usage(): string {
  return [
    "Usage: tavo-ui native generate [--config <path>] [--out <path>]",
    "",
    "Reads tavo-ui.config.json by default and generates a project-owned React Native theme config module.",
    "",
    "Options:",
    "  --config <path>  Path to a Tavo.js UI config file.",
    "  --out <path>     Output JS module path. Defaults to ./tavo-ui.generated.js.",
    "  --help           Show this help message."
  ].join("\n");
}

function optionValue(args: string[], index: number, option: string): string {
  const value = args[index + 1];
  if (!value || value.startsWith("-")) {
    throw new Error(`Missing value for ${option}.`);
  }
  return value;
}

function parseArgs(argv: string[], cwd: string): CliOptions {
  const options: CliOptions = { cwd };
  const args = argv[0] === "generate" ? argv.slice(1) : argv;

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--help" || arg === "-h") {
      options.help = true;
      continue;
    }
    if (arg === "--config") {
      options.config = optionValue(args, index, arg);
      index += 1;
      continue;
    }
    if (arg === "--out") {
      options.out = optionValue(args, index, arg);
      index += 1;
      continue;
    }
    throw new Error(`Unknown option: ${arg}`);
  }

  return options;
}

function findConfig(cwd: string, requested?: string): string {
  if (requested) {
    const configPath = isAbsolute(requested) ? requested : resolve(cwd, requested);
    if (!existsSync(configPath)) {
      throw new Error(`Config file not found: ${configPath}`);
    }
    return configPath;
  }

  for (const candidate of CONFIG_CANDIDATES) {
    const configPath = resolve(cwd, candidate);
    if (existsSync(configPath)) {
      return configPath;
    }
  }

  throw new Error(`No Tavo.js UI config found. Looked for: ${CONFIG_CANDIDATES.join(", ")}`);
}

async function readConfig(configPath: string): Promise<TavoUiThemeConfig> {
  if (configPath.endsWith(".json")) {
    return JSON.parse(readFileSync(configPath, "utf8")) as TavoUiThemeConfig;
  }

  const imported = await import(pathToFileURL(configPath).href);
  return (imported.default ?? imported.config) as TavoUiThemeConfig;
}

function generatedModuleFormat(outPath: string): {
  declarationPath: string;
  exportLine: string;
  declarationExportLine: string;
} {
  const extension = extname(outPath).toLowerCase();
  if (extension === ".js") {
    return {
      declarationPath: outPath.slice(0, -3) + ".d.ts",
      exportLine: "export default autoConfig;",
      declarationExportLine: "export default autoConfig;"
    };
  }
  if (extension === ".mjs") {
    return {
      declarationPath: outPath.slice(0, -4) + ".d.mts",
      exportLine: "export default autoConfig;",
      declarationExportLine: "export default autoConfig;"
    };
  }
  if (extension === ".cjs") {
    return {
      declarationPath: outPath.slice(0, -4) + ".d.cts",
      exportLine: "module.exports = autoConfig;",
      declarationExportLine: "export = autoConfig;"
    };
  }
  throw new Error("Native config output must end in .js, .mjs, or .cjs.");
}

function writeFileIfChanged(filePath: string, content: string): void {
  if (!existsSync(filePath) || readFileSync(filePath, "utf8") !== content) {
    writeFileSync(filePath, content);
  }
}

function writeGeneratedConfig(outPath: string, config: TavoUiThemeConfig): void {
  mkdirSync(dirname(outPath), { recursive: true });
  const json = JSON.stringify(config, null, 2);
  const { declarationPath, exportLine, declarationExportLine } = generatedModuleFormat(outPath);
  const moduleSource = [
    "/* This file is generated by tavo-ui native generate. */",
    `const autoConfig = ${json};`,
    exportLine,
    ""
  ].join("\n");
  const declarationSource = [
    'import type { TavoUiThemeConfig } from "@tavojs/ui-react-native";',
    "declare const autoConfig: TavoUiThemeConfig;",
    declarationExportLine,
    ""
  ].join("\n");
  writeFileIfChanged(outPath, moduleSource);
  writeFileIfChanged(declarationPath, declarationSource);
}

export async function runNativeCli(argv = process.argv.slice(2), cwd = process.cwd()): Promise<void> {
  const options = parseArgs(argv, cwd);
  if (options.help) {
    console.log(usage());
    return;
  }

  const configPath = findConfig(options.cwd, options.config);
  const config = await readConfig(configPath);
  buildThemeTokens(config);

  const outPath = options.out
    ? isAbsolute(options.out)
      ? options.out
      : resolve(options.cwd, options.out)
    : resolve(options.cwd, "tavo-ui.generated.js");

  writeGeneratedConfig(outPath, config);
  console.log(`Generated React Native Tavo.js UI config from ${configPath}`);
  console.log(`Wrote ${outPath}`);
}

export async function run(argv = process.argv): Promise<void> {
  return runNativeCli(argv.slice(2));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  runNativeCli().catch((error: unknown) => {
    console.error(safeErrorMessage(error));
    process.exitCode = 1;
  });
}
